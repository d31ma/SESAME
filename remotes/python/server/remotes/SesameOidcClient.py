from typing import Annotated, Protocol

@http_client({"path":"/api/v1/oidc","adapter":"sesame","setup":"SesameSetup"})
class SesameOidcClient(Protocol):
    @post_request("/consent-get")
    async def consent_get(self, session: Annotated[str, request_header("Sesame-Session")], body: Annotated[object, request_body]) -> object: ...

    @post_request("/consent-grant")
    async def consent_grant(self, session: Annotated[str, request_header("Sesame-Session")], body: Annotated[object, request_body]) -> object: ...

    @post_request("/consent-withdraw")
    async def consent_withdraw(self, session: Annotated[str, request_header("Sesame-Session")], body: Annotated[object, request_body]) -> object: ...

    @post_request("/device-approve")
    async def device_approve(self, session: Annotated[str, request_header("Sesame-Session")], body: Annotated[object, request_body]) -> object: ...

    @post_request("/device-authorize")
    async def device_authorize(self, body: Annotated[object, request_body]) -> object: ...

    @post_request("/device-deny")
    async def device_deny(self, session: Annotated[str, request_header("Sesame-Session")], body: Annotated[object, request_body]) -> object: ...

    @post_request("/device-lookup")
    async def device_lookup(self, session: Annotated[str, request_header("Sesame-Session")], body: Annotated[object, request_body]) -> object: ...

    @post_request("/dpop-verify")
    async def dpop_verify(self, body: Annotated[object, request_body]) -> object: ...

    @post_request("/interaction-complete")
    async def interaction_complete(self, session: Annotated[str, request_header("Sesame-Session")], body: Annotated[object, request_body]) -> object: ...

    @post_request("/interaction-get")
    async def interaction_get(self, session: Annotated[str, request_header("Sesame-Session")], body: Annotated[object, request_body]) -> object: ...

    @post_request("/pushed-authorize")
    async def pushed_authorize(self, body: Annotated[object, request_body]) -> object: ...

    @post_request("/refresh-family-get")
    async def refresh_family_get(self, session: Annotated[str, request_header("Sesame-Session")], body: Annotated[object, request_body]) -> object: ...

    @post_request("/refresh-family-revoke")
    async def refresh_family_revoke(self, session: Annotated[str, request_header("Sesame-Session")], body: Annotated[object, request_body]) -> object: ...
