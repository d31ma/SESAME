from typing import Annotated, Protocol

@http_client({"path":"/api/v1/scim","adapter":"sesame","setup":"SesameSetup"})
class SesameScimClient(Protocol):
    @post_request("/client-disable")
    async def client_disable(self, session: Annotated[str, request_header("Sesame-Session")], body: Annotated[object, request_body]) -> object: ...

    @post_request("/client-register")
    async def client_register(self, session: Annotated[str, request_header("Sesame-Session")], body: Annotated[object, request_body]) -> object: ...

    @post_request("/client-rotate-token")
    async def client_rotate_token(self, session: Annotated[str, request_header("Sesame-Session")], body: Annotated[object, request_body]) -> object: ...

    @post_request("/group-create")
    async def group_create(self, authorization: Annotated[str, request_header("Authorization")], body: Annotated[object, request_body]) -> object: ...

    @post_request("/group-deprovision")
    async def group_deprovision(self, authorization: Annotated[str, request_header("Authorization")], body: Annotated[object, request_body]) -> object: ...

    @post_request("/group-get")
    async def group_get(self, authorization: Annotated[str, request_header("Authorization")], body: Annotated[object, request_body]) -> object: ...

    @post_request("/group-list")
    async def group_list(self, authorization: Annotated[str, request_header("Authorization")], body: Annotated[object, request_body]) -> object: ...

    @post_request("/group-patch")
    async def group_patch(self, authorization: Annotated[str, request_header("Authorization")], body: Annotated[object, request_body]) -> object: ...

    @post_request("/user-create")
    async def user_create(self, authorization: Annotated[str, request_header("Authorization")], body: Annotated[object, request_body]) -> object: ...

    @post_request("/user-deprovision")
    async def user_deprovision(self, authorization: Annotated[str, request_header("Authorization")], body: Annotated[object, request_body]) -> object: ...

    @post_request("/user-get")
    async def user_get(self, authorization: Annotated[str, request_header("Authorization")], body: Annotated[object, request_body]) -> object: ...

    @post_request("/user-list")
    async def user_list(self, authorization: Annotated[str, request_header("Authorization")], body: Annotated[object, request_body]) -> object: ...

    @post_request("/user-patch")
    async def user_patch(self, authorization: Annotated[str, request_header("Authorization")], body: Annotated[object, request_body]) -> object: ...
